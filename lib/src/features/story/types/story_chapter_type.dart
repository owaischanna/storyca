class StoryChapterType {
  final int index;
  final String name;
  final String date;
  final String views;
  final bool isCurrent;
  final String words;
  final String status;

  StoryChapterType({
    required this.index,
    required this.name,
    required this.date,
    required this.views,
    required this.isCurrent,
    required this.words,
    required this.status,
  });
}
